"""Turn a manifest into a compiled binary, using Nuitka as the backend.

One manifest, six targets, no hand-written compiler flags. The strategies that
matter:

- The generated entry script imports the App **statically**, because Nuitka
  bundles only what it can see through imports.
- Every target writes to ``dist/<target>/``, because Nuitka names its output
  after the app for every mode and would otherwise overwrite earlier artefacts.
- The entry script is named after the app, which is what makes ``my-app.dist`` /
  ``my-app.AppImage`` come out with the right name.
"""

from __future__ import annotations

import importlib.util
import re
import shutil
import subprocess
import sys
from pathlib import Path

from .manifest import Manifest

ENTRY_TEMPLATE = """\
# Generated by zagred build. Do not edit.
# The import is static on purpose: Nuitka bundles what it can see.
from {module} import {attribute} as app
from zagred.runtime import boot

boot(app, ui="ui", debug={debug!r})
"""

# target -> (nuitka mode, extra flags).
# Note that AppImage uses ``app-dist``, not ``app``: Nuitka refuses to build a
# Linux installer from a onefile payload. And ``app`` is only meaningful on
# macOS, where it produces a .app bundle.
TARGETS: dict[str, tuple[str, list[str]]] = {
    "onefile": ("onefile", []),
    "standalone": ("standalone", []),
    "exe": ("standalone", ["--windows-create-installer"]),
    "appimage": ("app-dist", ["--linux-create-installer"]),
    "app": ("app", []),
    "dmg": ("app", ["--macos-create-installer"]),
}

# Used when ``--target auto`` is passed: the most useful artifact per platform.
DEFAULT_TARGET = {"linux": "appimage", "win32": "onefile", "darwin": "app"}


def pick_target(requested: str) -> str:
    """Resolve a ``--target`` value into one of :data:`TARGETS`.

    Args:
        requested: A key of :data:`TARGETS`, or ``"auto"`` to choose the best
            default for the current platform.

    Returns:
        The concrete target name, e.g. ``"appimage"``.

    Raises:
        ValueError: If ``requested`` is not a known target.
        RuntimeError: If ``requested`` is ``"auto"`` and the platform has no
            default (cross-compiling is not supported).
    """
    if requested != "auto":
        if requested not in TARGETS:
            raise ValueError(f"unknown target {requested!r}; pick one of {sorted(TARGETS)}")
        return requested
    platform = sys.platform
    for prefix, target in DEFAULT_TARGET.items():
        if platform.startswith(prefix):
            return target
    raise RuntimeError(f"no default build target for {platform}; pass --target")


def build(
    manifest: Manifest,
    root: Path,
    target: str = "auto",
    debug: bool = False,
    jobs: int | None = None,
) -> int:
    """Build the frontend, compile it with Nuitka, and write the artifacts.

    Steps, in order: run ``[ui] build`` (if set), generate the entry script,
    invoke Nuitka with the flags for the chosen target, then print what landed
    in the output directory.

    Args:
        manifest: Parsed project manifest, normally from
            :func:`zagred.manifest.load_manifest`.
        root: Project root. Frontend commands run in ``root/[ui] dir`` and all
            paths in the manifest are resolved against this.
        target: One of :data:`TARGETS`, or ``"auto"`` to pick by platform.
        debug: Bake ``debug=True`` into the app so it opens the WebView
            inspector. Development only — a warning is printed because this is
            easy to ship by accident.
        jobs: Parallel C compiler jobs, overriding ``[build] jobs``. ``None``
            means "no opinion"; negative values mean CPU count minus N.

    Returns:
        Process exit code: ``0`` on success, the frontend builder's code if the
        frontend failed, ``1`` if Nuitka is missing, ``2`` if the UI dist is
        absent, otherwise Nuitka's own exit code.
    """
    if importlib.util.find_spec("nuitka") is None:
        print(
            "[zagred] Nuitka is not installed in this environment.\n"
            "  uv sync --group build\n"
            "  uv run zagred build",
            file=sys.stderr,
        )
        return 1

    if manifest.ui_build_command:
        cwd = root / manifest.ui_dir
        print(f"[zagred] frontend: {manifest.ui_build_command}")
        code = subprocess.run(
            manifest.ui_build_command, shell=True, cwd=cwd if cwd.is_dir() else root
        ).returncode
        if code != 0:
            print("[zagred] frontend build failed", file=sys.stderr)
            return code

    target = pick_target(target)
    mode, extra = TARGETS[target]

    if debug:
        print(
            "[zagred] WARNING: debug build — the WebView inspector opens at startup.\n"
            "         Rebuild without --debug before shipping.",
            file=sys.stderr,
        )

    work = root / ".zagred" / "build"
    work.mkdir(parents=True, exist_ok=True)
    # Nuitka names every artefact after the script it compiles, so the entry
    # script carries the app name: <name>.dist / <name>.AppImage / <name>.exe.
    entry_script = work / f"{re.sub(r'[^A-Za-z0-9_-]', '_', manifest.name)}.py"
    entry_script.write_text(
        ENTRY_TEMPLATE.format(
            module=manifest.module,
            attribute=manifest.attribute,
            debug=debug,
        ),
        encoding="utf-8",
    )

    ui_dist = root / manifest.ui_dist
    if not ui_dist.is_dir():
        print(f"[zagred] UI dist not found: {ui_dist}", file=sys.stderr)
        return 2

    out_dir = root / manifest.output / target
    out_dir.mkdir(parents=True, exist_ok=True)
    argv = [
        sys.executable, "-m", "nuitka",
        f"--mode={mode}",
        "--assume-yes-for-downloads",
        f"--output-dir={out_dir}",
        f"--include-data-dir={ui_dist}=ui",
        f"--product-name={manifest.name}",
        f"--output-filename={manifest.name}",
        f"--file-version={manifest.version}",
        f"--product-version={manifest.version}",
        "--company-name=zagred",
        "--remove-output",
        *extra,
    ]
    if manifest.low_memory:
        argv.append("--low-memory")
    jobs = jobs if jobs is not None else manifest.jobs
    if jobs is not None:
        argv.append(f"--jobs={jobs}")
    if sys.platform.startswith("win"):
        argv.append("--windows-console-mode=disable")

    icon = root / manifest.icon if manifest.icon else None
    if icon and icon.is_file():
        if sys.platform.startswith("win"):
            argv.append(f"--windows-icon-from-ico={icon}")
        elif sys.platform == "darwin":
            argv.append(f"--macos-app-icon={icon}")
        else:
            argv.append(f"--linux-app-icon={icon}")
    argv.append(str(entry_script))

    print("[zagred] " + " ".join(argv))
    code = subprocess.run(argv, cwd=root).returncode
    if code == 0:
        print(f"[zagred] done -> {out_dir}")
        for produced in sorted(out_dir.iterdir()):
            print(f"  {produced.name}")
    return code


def renderer() -> tuple[bool, str, str]:
    """Check whether a real webview engine is importable from *this* interpreter.

    ``import webview`` always succeeds because pywebview defers backend loading;
    only importing the backend itself proves the app can open a window. On Linux
    this is the check that catches the uv/``python3-gi`` split, where GTK is
    installed system-wide but invisible from uv's standalone Python.

    Returns:
        A ``(usable, name, fix)`` tuple. ``usable`` is ``False`` when a window
        cannot be created, ``name`` is the backend that was probed
        (``"gtk"``, ``"edgechromium"``, ``"cocoa"``), and ``fix`` is a
        ready-to-paste instruction block, empty when nothing is wrong.
    """
    if sys.platform.startswith("linux"):
        try:
            import gi  # noqa: F401

            return True, "gtk", ""
        except ImportError:
            return False, "gtk", (
                "sudo apt install python3-gi gir1.2-webkit2-4.1\n"
                "  then recreate the venv so it can see system packages:\n"
                "  rm -rf .venv && uv venv --python /usr/bin/python3 --system-site-packages && uv sync"
            )
    if sys.platform.startswith("win"):
        try:
            import clr  # noqa: F401

            return True, "edgechromium", ""
        except ImportError:
            return False, "edgechromium", (
                "uv add pythonnet  # plus the WebView2 runtime from Microsoft"
            )
    try:
        import objc  # noqa: F401

        return True, "cocoa", ""
    except ImportError:
        return True, "cocoa", ""


def doctor() -> int:
    """Print a report of everything ``zagred dev`` and ``zagred build`` need.

    Checks the interpreter, pywebview, the actual webview backend, Nuitka, and
    on Linux ``patchelf`` and ``appimagetool``. Missing optional pieces print
    the command that fixes them rather than failing.

    Returns:
        ``0`` always — the report is informational, so it is safe to call from
        scripts without aborting on a missing build tool.
    """
    from . import __version__

    print(f"zagred      {__version__}")
    print(f"python      {sys.version.split()[0]}")
    print(f"platform    {sys.platform}")

    try:
        from importlib.metadata import version

        print(f"pywebview   {version('pywebview')}")
    except Exception as exc:  # noqa: BLE001
        print(f"pywebview   MISSING ({exc})")

    ok, name, fix = renderer()
    print(f"renderer    {name}{'' if ok else ' MISSING — cannot open a window'}")
    if fix:
        for line in fix.splitlines():
            print(f"  {line}")

    nuitka = shutil.which("nuitka") or _module_version("nuitka")
    print(f"nuitka      {nuitka or 'MISSING (uv sync --group build)'}")

    if sys.platform.startswith("linux"):
        patchelf = shutil.which("patchelf")
        print(f"patchelf    {patchelf or 'MISSING (required by Nuitka: pip install patchelf)'}")
        tool = shutil.which("appimagetool")
        print(f"appimagetool{' (downloaded+cached by Nuitka if absent)' if not tool else ''} {tool or '-'}")
    return 0


def _module_version(name: str) -> str | None:
    """Return an importable module's ``__version__``, or ``None`` if absent.

    Args:
        name: Importable module name, e.g. ``"nuitka"``.

    Returns:
        The version string, ``"installed"`` when the module provides no
        ``__version__``, or ``None`` when the import fails.
    """
    try:
        module = __import__(name)
        return getattr(module, "__version__", "installed")
    except ImportError:
        return None
